static const char* gradeFor(int score) {
    if (score >= 90) return "Отличное понимание темы";
    if (score >= 70) return "Уверенное понимание материала";
    if (score >= 50) return "Базовые знания, рекомендуется повторение";
    return "Стоит повторить материал";
}

static bool askQuestion(const Question& q, int number, bool& correctOut) {
    std::cout << "\n--- Этап " << q.stage << ": " << q.stageTitle << " ---\n";
    std::cout << "Вопрос " << number << "/10\n";
    std::cout << q.prompt << "\n";
    if (!q.code.empty()) {
        std::cout << "\n" << q.code << "\n";
    }
    std::cout << "\n";
    for (int i = 0; i < 3; ++i) {
        std::cout << (i + 1) << ") " << q.options[i] << "\n";
    }

    int answer = 0;
    if (!readChoice("Ваш ответ (1-3): ", 1, 3, answer)) return false;

    correctOut = (answer == q.correct);
    if (correctOut) std::cout << "Верно!\n";
    else            std::cout << "Неверно.\n";
    std::cout << "Правильный ответ: " << q.correct << ") "
              << q.options[q.correct - 1] << "\n";
    std::cout << "Пояснение: " << q.explanation << "\n";

    return waitEnter();
}

static bool playGame() {
    std::vector<Question> questions = makeQuestions();
    int score = 0;
    int correctCount = 0;

    for (std::size_t i = 0; i < questions.size(); ++i) {
        bool correct = false;
        if (!askQuestion(questions[i], static_cast<int>(i) + 1, correct)) {
            std::cout << "\nИгра прервана (EOF). Итоговая оценка не присваивается.\n";
            return false;
        }
        if (correct) {
            score += 10;
            ++correctCount;
        }
    }

    std::cout << "\n===== Результат =====\n";
    std::cout << "Правильно: " << correctCount << " из 10\n";
    std::cout << "Баллы: " << score << " из 100\n";
    std::cout << "Оценка: " << gradeFor(score) << "\n";
    return true;
}

int main() {
    std::ios::sync_with_stdio(false);

    for (;;) {
        showMenu();
        int choice = 0;
        if (!readChoice("Выбор: ", 0, 2, choice)) {
            std::cout << "\nEOF. Завершение.\n";
            return 0;
        }
        if (choice == 0) {
            std::cout << "До свидания!\n";
            return 0;
        } else if (choice == 2) {
            showRules();
        } else {
            if (!playGame()) return 0;
        }
    }
}