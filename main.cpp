static bool readLine(std::string& line) {
    return static_cast<bool>(std::getline(std::cin, line));
}

static int parseSingleDigit(const std::string& line) {
    std::size_t i = 0, n = line.size();
    while (i < n && (line[i] == ' ' || line[i] == '\t')) ++i;
    if (i == n) return -1;
    char c = line[i];
    if (c < '0' || c > '9') return -1;
    ++i;
    while (i < n && (line[i] == ' ' || line[i] == '\t')) ++i;
    if (i != n) return -1;
    return c - '0';
}

static bool readChoice(const std::string& prompt, int minV, int maxV, int& out) {
    for (;;) {
        std::cout << prompt;
        std::string line;
        if (!readLine(line)) return false;
        int v = parseSingleDigit(line);
        if (v >= minV && v <= maxV) { out = v; return true; }
        std::cout << "Недопустимый ввод. Введите одну цифру от "
                  << minV << " до " << maxV << ".\n";
    }
}

static bool waitEnter() {
    for (;;) {
        std::cout << "\nНажмите Enter, чтобы продолжить...";
        std::string line;
        if (!readLine(line)) return false;
        bool onlyWs = true;
        for (char c : line) {
            if (c != ' ' && c != '\t') { onlyWs = false; break; }
        }
        if (onlyWs) return true;
        std::cout << "Нажмите Enter (пустая строка) для продолжения.\n";
    }
}

